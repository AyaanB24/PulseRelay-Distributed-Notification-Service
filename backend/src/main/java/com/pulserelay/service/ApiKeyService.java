package com.pulserelay.service;

import com.pulserelay.config.TenantPrincipal;
import com.pulserelay.entity.ApiKey;
import com.pulserelay.entity.Tenant;
import com.pulserelay.exception.ApiKeyException;
import com.pulserelay.repository.ApiKeyRepository;
import com.pulserelay.repository.TenantRepository;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.security.SecureRandom;
import java.util.Base64;
import java.util.HexFormat;
import java.util.Optional;

/**
 * Service for managing API keys.
 * Handles generation, validation, and storage of cryptographically secure API keys.
 */
@Service
@Slf4j
@RequiredArgsConstructor
public class ApiKeyService {

    private final ApiKeyRepository apiKeyRepository;
    private final TenantRepository tenantRepository;

    /**
     * Prefix for all API keys generated by PulseRelay.
     * Makes keys easily identifiable in logs and documentation.
     */
    private static final String API_KEY_PREFIX = "pr_live_";

    /**
     * Length of random bytes to generate (256 bits = 32 bytes).
     */
    private static final int KEY_LENGTH_BYTES = 32;

    /**
     * Generate a new cryptographically secure API key.
     * Format: pr_live_<random_base64_encoded_bytes>
     * 
     * @return Original API key (only shown once to the user)
     */
    public String generateRawApiKey() {
        try {
            SecureRandom secureRandom = new SecureRandom();
            byte[] randomBytes = new byte[KEY_LENGTH_BYTES];
            secureRandom.nextBytes(randomBytes);

            // Encode as base64 for a readable format
            String encodedKey = Base64.getUrlEncoder()
                .withoutPadding()
                .encodeToString(randomBytes);

            return API_KEY_PREFIX + encodedKey;
        } catch (Exception e) {
            log.error("Failed to generate API key", e);
            throw new ApiKeyException("Failed to generate API key", e);
        }
    }

    /**
     * Hash an API key using SHA-256.
     * This hash is stored in the database.
     * The original key is never stored.
     * 
     * @param rawApiKey The original API key
     * @return SHA-256 hash as hexadecimal string
     */
    public String hashApiKey(String rawApiKey) {
        try {
            MessageDigest digest = MessageDigest.getInstance("SHA-256");
            byte[] hashBytes = digest.digest(rawApiKey.getBytes());
            return HexFormat.of().formatHex(hashBytes);
        } catch (NoSuchAlgorithmException e) {
            log.error("SHA-256 algorithm not available", e);
            throw new ApiKeyException("Failed to hash API key", e);
        }
    }

    /**
     * Create and store a new API key for a tenant.
     * 
     * @param tenant The tenant this key belongs to
     * @param keyName Human-readable name for this key
     * @return The original API key (only shown once)
     */
    @Transactional
    public String createApiKey(Tenant tenant, String keyName) {
        if (tenant == null || tenant.getId() == null) {
            throw new ApiKeyException("Tenant is required to create API key");
        }

        // Check if a key with this name already exists for this tenant
        Optional<ApiKey> existingKey = apiKeyRepository.findByTenantAndName(tenant, keyName);
        if (existingKey.isPresent()) {
            throw new ApiKeyException("API key with name '" + keyName + "' already exists for this tenant");
        }

        // Generate raw key
        String rawApiKey = generateRawApiKey();

        // Hash the key
        String keyHash = hashApiKey(rawApiKey);

        // Store only the hash
        ApiKey apiKey = ApiKey.builder()
            .tenant(tenant)
            .keyHash(keyHash)
            .name(keyName)
            .status(ApiKey.ApiKeyStatus.ACTIVE)
            .build();

        apiKeyRepository.save(apiKey);
        log.info("API key created for tenant: {}", tenant.getId());

        // Return only the original key (never stored, never logged)
        return rawApiKey;
    }

    /**
     * Authenticate a request using an API key.
     * 
     * @param rawApiKey The API key provided in the request
     * @return The ApiKey entity if valid and active
     * @throws ApiKeyException if key is invalid, revoked, or tenant is suspended
     */
    @Transactional(readOnly = true)
    public ApiKey authenticateApiKey(String rawApiKey) {
        if (rawApiKey == null || rawApiKey.isBlank()) {
            throw new ApiKeyException("API key is required");
        }

        // Hash the provided key
        String keyHash = hashApiKey(rawApiKey);

        // Find the key with tenant information
        ApiKey apiKey = apiKeyRepository.findActiveKeyWithTenant(keyHash)
            .orElseThrow(() -> new ApiKeyException("Invalid API key"));

        // Check if tenant is active
        Tenant tenant = apiKey.getTenant();
        if (tenant.getStatus() == Tenant.TenantStatus.SUSPENDED) {
            log.warn("Authentication attempt with suspended tenant: {}", tenant.getId());
            throw new ApiKeyException("Tenant is suspended");
        }

        log.debug("API key authenticated for tenant: {}", tenant.getId());
        return apiKey;
    }

    /**
     * Revoke an API key.
     * 
     * @param apiKeyId The ID of the key to revoke
     */
    @Transactional
    public void revokeApiKey(String apiKeyId) {
        ApiKey apiKey = apiKeyRepository.findById(java.util.UUID.fromString(apiKeyId))
            .orElseThrow(() -> new ApiKeyException("API key not found"));

        apiKey.setStatus(ApiKey.ApiKeyStatus.REVOKED);
        apiKeyRepository.save(apiKey);

        log.info("API key revoked: {}", apiKeyId);
    }

    /**
     * Get the current tenant status from a TenantPrincipal.
     * Used to verify tenant status when retrieving tenant information.
     * 
     * @param principal The authenticated tenant principal
     * @return Current tenant status (ACTIVE or SUSPENDED)
     * @throws ApiKeyException if tenant is not found
     */
    @Transactional(readOnly = true)
    public String getTenantStatusByPrincipal(TenantPrincipal principal) {
        Tenant tenant = tenantRepository.findById(principal.getTenantId())
            .orElseThrow(() -> new ApiKeyException("Tenant not found"));

        return tenant.getStatus().toString();
    }
}
